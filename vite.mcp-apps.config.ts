/**
 * Build of the MCP App widget bundles: each one is a self-contained HTML file
 * (scripts, styles and fonts inlined), written as a TypeScript module that
 * the MCP server serves as its ui:// resources.
 *
 * - default mode: the DOM widgets of mcp-apps/ (WIDGET_HTML);
 * - `--mode react`: the React widgets of mcp-apps/react/, built with the
 *   dashboard's components and Tailwind theme (REACT_WIDGET_HTML).
 *
 * `pnpm build:mcp-apps` builds both; `pnpm build` runs it before `next build`.
 */

import tailwindcss from "@tailwindcss/vite";
import react from "@vitejs/plugin-react";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { defineConfig, type Plugin } from "vite";
import { viteSingleFile } from "vite-plugin-singlefile";

const BUNDLES = {
  widgets: {
    root: resolve(__dirname, "mcp-apps"),
    module: resolve(__dirname, "lib/mcp/widgets/html.generated.ts"),
    exportName: "WIDGET_HTML",
  },
  react: {
    root: resolve(__dirname, "mcp-apps/react"),
    module: resolve(__dirname, "lib/mcp/widgets/react-html.generated.ts"),
    exportName: "REACT_WIDGET_HTML",
  },
} as const;

function writeHtmlModule(
  outDir: string,
  module: string,
  exportName: string,
): Plugin {
  return {
    name: "dev-recruit-widget-module",
    closeBundle() {
      const html = readFileSync(resolve(outDir, "index.html"), "utf8");
      writeFileSync(
        module,
        [
          "// Generated by `pnpm build:mcp-apps` from mcp-apps/: do not edit.",
          `export const ${exportName} = ${JSON.stringify(html)};`,
          "",
        ].join("\n"),
      );
    },
  };
}

export default defineConfig(({ mode }) => {
  const isReact = mode === "react";
  const bundle = isReact ? BUNDLES.react : BUNDLES.widgets;
  const outDir = resolve(bundle.root, "dist");

  return {
    root: bundle.root,
    logLevel: "warn",
    // The React bundle runs in the browser: no Node globals
    define: isReact ? { "process.env.NODE_ENV": JSON.stringify("production") } : {},
    plugins: [
      ...(isReact ? [react(), tailwindcss()] : []),
      viteSingleFile(),
      writeHtmlModule(outDir, bundle.module, bundle.exportName),
    ],
    resolve: {
      alias: { "@": resolve(__dirname, "./") },
    },
    build: {
      outDir,
      emptyOutDir: true,
      target: "es2022",
      // Fonts are inlined too: the sandbox allows no external origin
      assetsInlineLimit: () => true,
    },
  };
});
