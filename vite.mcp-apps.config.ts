/**
 * Build of the MCP App widget bundle (mcp-apps/): one self-contained HTML
 * file (scripts and styles inlined), written as a TypeScript module that the
 * MCP server serves as its ui:// resources. Run with `pnpm build:mcp-apps`;
 * `pnpm build` runs it before `next build`.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { defineConfig, type Plugin } from "vite";
import { viteSingleFile } from "vite-plugin-singlefile";

const ROOT = resolve(__dirname, "mcp-apps");
const OUT_DIR = resolve(ROOT, "dist");
const MODULE = resolve(__dirname, "lib/mcp/widgets/html.generated.ts");

function writeHtmlModule(): Plugin {
  return {
    name: "dev-recruit-widget-module",
    closeBundle() {
      const html = readFileSync(resolve(OUT_DIR, "index.html"), "utf8");
      writeFileSync(
        MODULE,
        [
          "// Generated by `pnpm build:mcp-apps` from mcp-apps/: do not edit.",
          `export const WIDGET_HTML = ${JSON.stringify(html)};`,
          "",
        ].join("\n"),
      );
    },
  };
}

export default defineConfig({
  root: ROOT,
  logLevel: "warn",
  plugins: [viteSingleFile(), writeHtmlModule()],
  build: {
    outDir: OUT_DIR,
    emptyOutDir: true,
    target: "es2022",
  },
});
